import { handler, ok, readJson } from "@/lib/api/response";
import {
  createRequestSchema,
  listQuerySchema,
  searchParamsToObject,
} from "@/lib/validation/requests";
import { createRequest, listRequests } from "@/server/requests/service";

/** GET /api/requests?q=&status=&reason=&sort=&order=&page=&pageSize= */
export const GET = handler(async (request: Request) => {
  const query = listQuerySchema.parse(searchParamsToObject(new URL(request.url).searchParams));
  const { items, meta } = await listRequests(query);
  return ok(items, { meta });
});

/** POST /api/requests — the reference is generated by the database, never accepted from the client. */
export const POST = handler(async (request: Request) => {
  const input = createRequestSchema.parse(await readJson(request));
  const created = await createRequest(input);
  return Response.json(
    { success: true, data: created },
    { status: 201, headers: { Location: `/api/requests/${created.id}` } },
  );
});
